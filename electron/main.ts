import { app, BrowserWindow, ipcMain, dialog, shell, nativeTheme, Menu } from 'electron';
import { autoUpdater } from 'electron-updater';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEV_URL = process.env.FOCUS_DEV_URL;

/** Occlusion detection on Windows can stall canvas repaints when the window is partly covered. */
app.commandLine.appendSwitch('disable-features', 'CalculateNativeWinOcclusion');
/** Keep the compositor running at the display refresh rate for low-latency inking. */
app.commandLine.appendSwitch('disable-frame-rate-limit');

const userDir = () => app.getPath('userData');
const boardsDir = () => path.join(userDir(), 'boards');
const settingsFile = () => path.join(userDir(), 'settings.json');

async function ensureDirs() {
  await fs.mkdir(boardsDir(), { recursive: true });
}

/** Board ids are generated by the renderer; never let one escape the boards directory. */
function boardPath(id: string) {
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(id)) throw new Error(`Identifiant de tableau invalide: ${id}`);
  return path.join(boardsDir(), `${id}.focusboard.json`);
}

let mainWindow: BrowserWindow | null = null;

function createWindow() {
  const win = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 900,
    minHeight: 600,
    show: false,
    backgroundColor: '#101114',
    autoHideMenuBar: true,
    titleBarStyle: 'hidden',
    titleBarOverlay: { color: '#17181c', symbolColor: '#c9ccd4', height: 40 },
    webPreferences: {
      preload: path.join(__dirname, 'preload.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
      spellcheck: true,
    },
  });

  win.once('ready-to-show', () => win.show());

  win.webContents.setWindowOpenHandler(({ url }) => {
    if (url.startsWith('http://') || url.startsWith('https://')) shell.openExternal(url);
    return { action: 'deny' };
  });

  if (DEV_URL) {
    win.loadURL(DEV_URL);
  } else {
    win.loadFile(path.join(__dirname, '..', 'dist', 'index.html'));
  }

  mainWindow = win;
  win.on('closed', () => {
    if (mainWindow === win) mainWindow = null;
  });
  return win;
}

